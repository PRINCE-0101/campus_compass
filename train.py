"""Reproducible model comparison; validation chooses model and rejection threshold."""
import hashlib
import json
import platform
import time
from collections import Counter
import joblib
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import sklearn
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, ConfusionMatrixDisplay, f1_score
from core import ROOT, LABELS, SEED, clean_text, routed_predictions

def build_data():
    source = json.loads((ROOT / 'data/queries.json').read_text())
    rows = [{'text': text, 'label': label, 'source': 'original_ai_assisted_campus_queries'}
            for label in LABELS for text in source[label]]
    df = pd.DataFrame(rows)
    df['clean_text'] = df.text.map(clean_text)
    if (df.clean_text == '').any():
        raise ValueError('Empty cleaned samples found')
    conflicts = df.groupby('clean_text').label.nunique()
    if (conflicts > 1).any():
        raise ValueError('Conflicting labels for duplicate text')
    duplicates = int(df.clean_text.duplicated().sum())
    df = df.drop_duplicates('clean_text').reset_index(drop=True)
    train, remaining = train_test_split(df.index, test_size=0.4, random_state=SEED, stratify=df.label)
    valid, test = train_test_split(remaining, test_size=0.5, random_state=SEED, stratify=df.loc[remaining, 'label'])
    df['split'] = 'train'
    df.loc[valid, 'split'] = 'validation'
    df.loc[test, 'split'] = 'test'
    df.to_csv(ROOT / 'data/campus_queries.csv', index=False)
    audit = {'rows_before_cleaning': len(rows), 'rows_after_cleaning': len(df),
             'duplicates_removed': duplicates, 'missing_values': int(df.isna().sum().sum()),
             'class_counts': dict(Counter(df.label)), 'split_counts': dict(Counter(df.split)),
             'source_sha256': hashlib.sha256((ROOT / 'data/queries.json').read_bytes()).hexdigest(),
             'min_words': int(df.clean_text.str.split().str.len().min()),
             'max_words': int(df.clean_text.str.split().str.len().max())}
    (ROOT / 'reports/data_audit.json').write_text(json.dumps(audit, indent=2))
    return df

def main():
    for directory in ['models', 'reports', 'data']:
        (ROOT / directory).mkdir(exist_ok=True)
    df = build_data()
    tr, va, te = [df[df.split == s] for s in ['train', 'validation', 'test']]
    estimators = {'logistic_regression': LogisticRegression(C=4, max_iter=2000, random_state=SEED),
                  'multinomial_nb': MultinomialNB(alpha=0.3)}
    fitted, selection, sweep = {}, {}, []
    for name, clf in estimators.items():
        pipeline = Pipeline([('tfidf', TfidfVectorizer(preprocessor=clean_text, ngram_range=(1, 2), sublinear_tf=True)), ('classifier', clf)])
        start = time.perf_counter()
        pipeline.fit(tr.text, tr.label)
        seconds = time.perf_counter() - start
        candidates = []
        for threshold in [0.0, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50]:
            pred = routed_predictions(pipeline, va.text, threshold)
            score = f1_score(va.label, pred, labels=LABELS, average='macro', zero_division=0)
            candidates.append((score, threshold))
            sweep.append({'model': name, 'threshold': threshold, 'validation_macro_f1': score})
        score, threshold = max(candidates, key=lambda x: (x[0], -x[1]))
        selection[name] = {'validation_macro_f1': score, 'threshold': threshold, 'fit_seconds': seconds}
        fitted[name] = pipeline
    # Freeze choice BEFORE evaluating test. No refit on validation/test.
    winner = max(selection, key=lambda name: selection[name]['validation_macro_f1'])
    metrics = {'seed': SEED, 'selected_model': winner, 'selection': selection,
               'python': platform.python_version(), 'sklearn': sklearn.__version__, 'test': {}}
    lines = ['# Evaluation report', '', 'Generated by `python train.py` on the included original, AI-assisted English query dataset.',
             'This is a small synthetic benchmark, not real student traffic and not a CLINC150 benchmark.',
             f'\nSeed: {SEED}. Train: {len(tr)}; validation: {len(va)}; held-out test: {len(te)}.',
             f'\nSelected using validation macro-F1: **{winner}**. The test set did not choose the model or threshold.',
             '\n| Model | Validation macro-F1 | Threshold | Test accuracy | Test macro precision | Test macro recall | Test macro-F1 |',
             '|---|---:|---:|---:|---:|---:|---:|']
    for name, pipeline in fitted.items():
        pred = routed_predictions(pipeline, te.text, selection[name]['threshold'])
        raw = pipeline.predict(te.text)
        report = classification_report(te.label, pred, labels=LABELS, output_dict=True, zero_division=0)
        metrics['test'][name] = {'accuracy': accuracy_score(te.label, pred), 'raw_accuracy': accuracy_score(te.label, raw), 'report': report}
        m = report['macro avg']
        lines.append(f"| {name} | {selection[name]['validation_macro_f1']:.3f} | {selection[name]['threshold']:.2f} | {accuracy_score(te.label,pred):.3f} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1-score']:.3f} |")
        pd.DataFrame(report).T.to_csv(ROOT / f'reports/{name}_classification_report.csv')
        results = te[['text', 'label']].copy()
        results['prediction'] = pred
        results['raw_prediction'] = raw
        results['top_model_confidence'] = pipeline.predict_proba(te.text).max(axis=1)
        results['correct'] = results.label == results.prediction
        results.to_csv(ROOT / f'reports/{name}_predictions.csv', index=False)
        matrix = confusion_matrix(te.label, pred, labels=LABELS)
        pd.DataFrame(matrix, index=LABELS, columns=LABELS).to_csv(ROOT / f'reports/{name}_confusion_matrix.csv')
        fig, ax = plt.subplots(figsize=(9, 7))
        ConfusionMatrixDisplay(matrix, display_labels=LABELS).plot(ax=ax, cmap='Blues', colorbar=False, xticks_rotation=35)
        ax.set_title(name.replace('_', ' ').title() + ' • held-out test')
        fig.tight_layout()
        fig.savefig(ROOT / f'reports/{name}_confusion_matrix.png', dpi=160)
        plt.close(fig)
        bundle = {'pipeline': pipeline, 'model': name, 'threshold': selection[name]['threshold'], 'seed': SEED, 'sklearn': sklearn.__version__}
        joblib.dump(bundle, ROOT / f'models/{name}.joblib')
        if name == winner:
            joblib.dump(bundle, ROOT / 'models/best.joblib')
            winning_results = results
    lines += ['\n## Actual correct predictions', '', '| Query | Truth | Prediction |', '|---|---|---|']
    for row in winning_results[winning_results.correct].head(8).itertuples():
        lines.append(f'| {row.text} | {row.label} | {row.prediction} |')
    lines += ['\n## Actual errors', '', '| Query | Truth | Prediction | Top model score |', '|---|---|---|---:|']
    errors = winning_results[~winning_results.correct]
    for row in errors.itertuples():
        lines.append(f'| {row.text} | {row.label} | {row.prediction} | {row.top_model_confidence:.3f} |')
    if errors.empty:
        lines.append('| No errors on this particular small split | — | — | — |')
    pairs = errors.groupby(['label', 'prediction']).size().sort_values(ascending=False)
    lines += ['\n## Error analysis', f'\n{len(errors)} of {len(te)} test queries were misclassified.']
    for (truth, predicted), count in pairs.items():
        lines.append(f'- {truth} → {predicted}: {count} cases.')
    lines += ['\nTF-IDF learns lexical associations, not full intent or campus knowledge. Shared terms such as registration, certificate and workshop blur categories. Low vocabulary coverage and a broad other class are further limitations. Inspect the examples above before proposing changes.',
              '\n## Limits and next experiment',
              'Scores are exploratory: the dataset is small, authored in one session and English-only. Related topics can occur across splits; exact normalized duplicates are blocked, but this is not a paraphrase-group or unseen-topic benchmark. Collect independently written student queries, group paraphrases before splitting, label ambiguous cases with a second annotator, and evaluate on a NEW untouched test set.',
              '\nConfidence is the model’s maximum predict_proba score, not a calibrated correctness guarantee. For a rejected query it refers to the original top model class, not the fallback other label. Unknown vocabulary is rejected independently. A low-confidence rule does not reliably detect every unknown intent.',
              '\nThe selected threshold was tuned on validation macro-F1 (including other); there is no separately measured open-world OOD recall. Do not interpret this as production readiness.']
    (ROOT / 'reports/evaluation.md').write_text('\n'.join(lines))
    (ROOT / 'reports/metrics.json').write_text(json.dumps(metrics, indent=2))
    pd.DataFrame(sweep).to_csv(ROOT / 'reports/threshold_search.csv', index=False)
    print(json.dumps({'winner': winner, 'selection': selection, 'test_accuracy': metrics['test'][winner]['accuracy'], 'test_macro_f1': metrics['test'][winner]['report']['macro avg']['f1-score']}, indent=2))

if __name__ == '__main__':
    main()
